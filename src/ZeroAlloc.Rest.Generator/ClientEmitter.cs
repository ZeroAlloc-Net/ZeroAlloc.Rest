    }

    private static string Capitalize(string s)
    {
        if (s.Length == 0) return s;
        return char.ToUpper(s[0]) + s.Substring(1).ToLower();
    }

    private static string StripGlobal(string typeName)
        => typeName.StartsWith("global::", System.StringComparison.Ordinal) ? typeName.Substring("global::".Length) : typeName;

    /// <summary>
    /// Derives a collision-free private field name from a type's name plus a suffix, deduplicating
    /// against already-assigned field names. Generic arguments are dropped, and any character that
    /// cannot appear in an identifier, such as the brackets of an array type, is removed.
    /// "global::MyApp.OverrideSerializer" gives "_overrideSerializer";
    /// "global::MyApp.JevError" with suffix "Mapper" gives "_jevErrorMapper";
    /// "global::MyApp.Wrapper&lt;global::MyApp.Foo&gt;" gives "_wrapper";
    /// "global::System.ValueTuple&lt;int, string&gt;" with suffix "Mapper" gives "_valueTupleMapper".
    /// Collisions get a numeric suffix: _overrideSerializer2, and so on.
    /// </summary>
    private static string GetFieldName(string fullTypeName, string suffix, List<string> existingFieldNames)
    {
        var name = StripGlobal(fullTypeName);
        var genericStart = name.IndexOf('<');
        if (genericStart >= 0)
            name = name.Substring(0, genericStart);
        name = name.Substring(name.LastIndexOf('.') + 1);
        var simple = new StringBuilder(name.Length + suffix.Length);
        foreach (var c in name)
        {
            if (char.IsLetterOrDigit(c) || c == '_')
                simple.Append(c);
        }
        simple.Append(suffix);
        if (simple.Length == 0) simple.Append("Serializer"); // defensive fallback
        var simpleName = simple.ToString();
        var candidate = "_" + char.ToLowerInvariant(simpleName[0]) + simpleName.Substring(1);
        if (!existingFieldNames.Contains(candidate)) return candidate;
        // Collision — append index
        var i = 2;
        while (existingFieldNames.Contains(candidate + i)) i++;
        return candidate + i;
    }

    // The constructor parameter for a field: the field name without its leading underscore,
    // escaped when that leaves a C# keyword, as a serializer type named @class would.
    private static string ParameterName(string fieldName)
    {
        var name = fieldName.Substring(1);
        return Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(name) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None
            ? "@" + name
            : name;
    }

    // The route as the contents of an interpolated string: each {token} a route parameter binds
    // becomes a hole holding its escaped value. An evaluated token stays the hole it has always
    // been, its text unchanged, so a URL that worked before ZRA005 is sent the same. Everything else
    // is literal text, braces doubled, so a token that would name an undefined variable, or the
    // client's own fields and locals, is sent as written. ZRA005 reports both.
    private static string RouteExpression(string route, List<ParameterModel> pathParams, EquatableArray<string> evaluatedTokens)
    {
        var sb = new StringBuilder(route.Length + 32);
        var next = 0;
        foreach (var token in RouteTemplate.Tokens(route))
        {
            var parameter = pathParams.Find(p => string.Equals(p.Name, token.Name, System.StringComparison.Ordinal));
            if (parameter is null && !Contains(evaluatedTokens, token.Name)) continue;
            AppendLiteral(sb, route.Substring(next, token.Start - next), interpolated: true);
            if (parameter is not null)
                // Parenthesized: a bare `global::` would end the hole's expression at its colon.
                sb.Append("{(global::System.Uri.EscapeDataString(__FormatValue(").Append(Identifier(parameter)).Append(")))}");
            else
                sb.Append('{').Append(token.Name).Append('}');
            next = token.Start + token.Length;
        }
        AppendLiteral(sb, route.Substring(next), interpolated: true);
        return sb.ToString();
    }

    private static bool Contains(EquatableArray<string> values, string value)
    {
        foreach (var v in values)
        {
            if (string.Equals(v, value, System.StringComparison.Ordinal))
                return true;
        }
        return false;
    }

    // Literal route text inside a regular string literal, or an interpolated one.
    private static void AppendLiteral(StringBuilder sb, string text, bool interpolated)
    {
        foreach (var c in text)
        {
            switch (c)
            {
                case '{' when interpolated: sb.Append("{{"); break;
                case '}' when interpolated: sb.Append("}}"); break;
                case '"': sb.Append("\\\""); break;
                case '\\': sb.Append("\\\\"); break;
                default: sb.Append(c); break;
            }
        }
    }

    // A parameter's name as a C# identifier: a parameter declared as @class is named "class".
    private static string Identifier(ParameterModel parameter)
        => Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(parameter.Name) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None
            ? "@" + parameter.Name
            : parameter.Name;

    private static ParameterModel? FindCancellationToken(EquatableArray<ParameterModel> parameters)
    {
        for (var i = 0; i < parameters.Count; i++)
            if (parameters[i].Kind == ParameterKind.CancellationToken) return parameters[i];
        return null;
    }

    private static List<ParameterModel> FilterParameters(EquatableArray<ParameterModel> parameters, ParameterKind kind)
    {
        var result = new List<ParameterModel>();
        for (var i = 0; i < parameters.Count; i++)
            if (parameters[i].Kind == kind) result.Add(parameters[i]);
        return result;
    }

    private static ParameterModel? FirstOrDefault(EquatableArray<ParameterModel> parameters, ParameterKind kind)
    {
        for (var i = 0; i < parameters.Count; i++)
            if (parameters[i].Kind == kind) return parameters[i];
        return null;
    }
