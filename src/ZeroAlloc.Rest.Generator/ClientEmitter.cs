using System.Collections.Generic;
using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using ZeroAlloc.Rest.Generator.Models;

namespace ZeroAlloc.Rest.Generator;

internal static class ClientEmitter
{
    // Every field a generated client declares before its injected dependencies.
    private static readonly string[] ReservedFieldNames =
        { "_activitySource", "_meter", "_requestsTotal", "_requestDurationMs", "_httpClient", "_serializer" };

    internal static void Emit(SourceProductionContext ctx, ClientModel model, bool dependencyInjection)
    {
        foreach (var diagnostic in model.Diagnostics)
            ctx.ReportDiagnostic(diagnostic.ToDiagnostic());

        // Collect unique method-level serializer types (ordered, deduped)
        var overrideSerializers = model.GetOverrideSerializerTypes();

        // Field names are unique across every fixed field the class declares and every injected
        // dependency.
        var usedFieldNames = new List<string>(ReservedFieldNames);
        var serializerFieldMap = new Dictionary<string, string>();
        foreach (var st in overrideSerializers)
        {
            var fieldName = GetFieldName(st, string.Empty, usedFieldNames);
            usedFieldNames.Add(fieldName);
            serializerFieldMap[st] = fieldName;
        }

        var errorMappings = model.GetUsedErrorMappings();
        var errorMapperFieldMap = new Dictionary<string, string>();
        foreach (var (errorType, _, _) in errorMappings)
        {
            var fieldName = GetFieldName(errorType, "Mapper", usedFieldNames);
            usedFieldNames.Add(fieldName);
            errorMapperFieldMap[errorType] = fieldName;
        }

        var hasQueryParams = false;
        foreach (var m in model.Methods)
            foreach (var p in m.Parameters)
                if (p.Kind == ParameterKind.Query) { hasQueryParams = true; break; }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Net.Http;");
        sb.AppendLine("using System.Net.Http.Headers;");
        sb.AppendLine("using System.Threading;");
        sb.AppendLine("using System.Threading.Tasks;");
        if (hasQueryParams)
            sb.AppendLine("using ZeroAlloc.Collections;");
        sb.AppendLine("using ZeroAlloc.Rest;");
        sb.AppendLine();

        if (!string.IsNullOrEmpty(model.Namespace))
        {
            sb.AppendLine($"namespace {model.Namespace};");
            sb.AppendLine();
        }

        sb.AppendLine(dependencyInjection
            ? $"{model.Accessibility} sealed partial class {model.ClassName} : {model.InterfaceName}, global::ZeroAlloc.Rest.IGeneratedRestClient<{model.ClassName}>"
            : $"{model.Accessibility} sealed partial class {model.ClassName} : {model.InterfaceName}");
        sb.AppendLine("{");
        sb.AppendLine("    private static readonly global::System.Diagnostics.ActivitySource _activitySource = new(\"ZeroAlloc.Rest\");");
        sb.AppendLine("    private static readonly global::System.Diagnostics.Metrics.Meter _meter = new(\"ZeroAlloc.Rest\");");
        sb.AppendLine("    private static readonly global::System.Diagnostics.Metrics.Counter<long> _requestsTotal = _meter.CreateCounter<long>(\"rest.requests_total\");");
        sb.AppendLine("    private static readonly global::System.Diagnostics.Metrics.Histogram<double> _requestDurationMs = _meter.CreateHistogram<double>(\"rest.request_duration_ms\");");
        sb.AppendLine("    private readonly System.Net.Http.HttpClient _httpClient;");
        sb.AppendLine("    private readonly ZeroAlloc.Rest.IRestSerializer _serializer;");
        // Override serializers are held and taken as IRestSerializer, like the main one, so an
        // internal serializer type never appears in the public constructor. Create resolves the
        // concrete types.
        foreach (var st in overrideSerializers)
            sb.AppendLine($"    private readonly ZeroAlloc.Rest.IRestSerializer {serializerFieldMap[st]};");
        // A mapper is taken as IHttpErrorMapper<E>, so an internal mapper type never appears in the
        // constructor. E is as accessible as the method that returns it. Create resolves the concrete
        // mapper type. E is spelled as the mapper declares it, nullable annotation included, because
        // IHttpErrorMapper<E> is invariant.
        foreach (var (errorType, _, mapperErrorType) in errorMappings)
            sb.AppendLine($"    private readonly global::ZeroAlloc.Rest.IHttpErrorMapper<{mapperErrorType}> {errorMapperFieldMap[errorType]};");
        sb.AppendLine();

        // Build constructor parameter list
        var ctorParams = new System.Collections.Generic.List<string>
        {
            "System.Net.Http.HttpClient httpClient",
            // Always IRestSerializer, even with an interface-level [Serializer]: that type may be
            // internal while the client is public. Create resolves the concrete type.
            "ZeroAlloc.Rest.IRestSerializer serializer"
        };
        foreach (var st in overrideSerializers)
        {
            var fieldName = serializerFieldMap[st];
            ctorParams.Add($"ZeroAlloc.Rest.IRestSerializer {ParameterName(fieldName)}");
        }
        foreach (var (errorType, _, mapperErrorType) in errorMappings)
        {
            var fieldName = errorMapperFieldMap[errorType];
            ctorParams.Add($"global::ZeroAlloc.Rest.IHttpErrorMapper<{mapperErrorType}> {ParameterName(fieldName)}");
        }

        sb.AppendLine($"    public {model.ClassName}({string.Join(", ", ctorParams)})");
        sb.AppendLine("    {");
        sb.AppendLine("        _httpClient = httpClient;");
        sb.AppendLine("        _serializer = serializer;");
        foreach (var st in overrideSerializers)
        {
            var fieldName = serializerFieldMap[st];
            sb.AppendLine($"        {fieldName} = {ParameterName(fieldName)};");
        }
        foreach (var (errorType, _, _) in errorMappings)
        {
            var fieldName = errorMapperFieldMap[errorType];
            sb.AppendLine($"        {fieldName} = {ParameterName(fieldName)};");
        }
        sb.AppendLine("    }");
        sb.AppendLine();

        if (dependencyInjection)
            EmitGeneratedClientMembers(sb, model, overrideSerializers, errorMappings);

        var anyCallerCancellation = false;
        foreach (var method in model.Methods)
            anyCallerCancellation |= EmitMethod(ctx, sb, model.InterfaceName, method, serializerFieldMap, errorMapperFieldMap, model.MaxErrorBodyBytes);

        EmitFormatHelpers(sb, model);

        EmitRecordFailure(sb);
        if (anyCallerCancellation)
            EmitRecordCancellation(sb);
        EmitRecordDurationWithoutResponse(sb);

        var anyReturnsResult = false;
        foreach (var m in model.Methods)
            if (m.ReturnsResult) { anyReturnsResult = true; break; }
        if (anyReturnsResult)
            EmitCreateHttpError(sb);
        if (errorMappings.Count > 0)
            EmitRecordMapperFailure(sb);

        if (hasQueryParams)
        {
            sb.AppendLine("    private static void AppendToUrl(ZeroAlloc.Collections.HeapPooledList<char> list, System.ReadOnlySpan<char> value)");
            sb.AppendLine("    {");
            sb.AppendLine("        for (var i = 0; i < value.Length; i++) list.Add(value[i]);");
            sb.AppendLine("    }");
            sb.AppendLine("    private static void AppendToUrl(ZeroAlloc.Collections.HeapPooledList<char> list, char value)");
            sb.AppendLine("        => list.Add(value);");
        }

        sb.AppendLine("}");

        ctx.AddSource($"{model.InterfaceName}.g.cs", sb.ToString());
    }

    // IGeneratedRestClient<TSelf>: how Add{I} and the Resilience bridge build the client and register
    // its serializers, with no reflection or ActivatorUtilities. They exist only with the
    // ZeroAlloc.Rest.DependencyInjection package, since they call Microsoft.Extensions. Implemented
    // explicitly, so the client gains no public Create or AddSerializers that could clash with the
    // interface's own methods.
    private static void EmitGeneratedClientMembers(StringBuilder sb, ClientModel model, IReadOnlyList<string> overrideSerializers, IReadOnlyList<(string ErrorTypeName, string MapperTypeName, string MapperErrorTypeName)> errorMappings)
    {
        var self = $"global::ZeroAlloc.Rest.IGeneratedRestClient<{model.ClassName}>";
        const string GetRequired = "global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService";
        const string TryAddSingleton = "global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddSingleton";

        var serializerArg = model.SerializerTypeName != null
            ? $"{GetRequired}<{model.SerializerTypeName}>(services)"
            : $"global::ZeroAlloc.Rest.RestSerializerServiceProviderExtensions.GetRequiredRestSerializer<{model.InterfaceName}>(services)";
        var ctorArgs = new List<string> { "httpClient", serializerArg };
        foreach (var st in overrideSerializers)
            ctorArgs.Add($"{GetRequired}<{st}>(services)");

        var createSignature = $"    static {model.ClassName} {self}.Create(global::System.Net.Http.HttpClient httpClient, global::System.IServiceProvider services)";
        if (errorMappings.Count == 0)
        {
            sb.AppendLine(createSignature);
            sb.AppendLine($"        => new {model.ClassName}(");
            for (var i = 0; i < ctorArgs.Count; i++)
                sb.AppendLine($"            {ctorArgs[i]}{(i < ctorArgs.Count - 1 ? "," : ");")}");
            sb.AppendLine();
        }
        else
        {
            // The concrete mapper type, never IHttpErrorMapper<E>: a host registration of the
            // interface can never replace a library's mapper. A mapper serving several error types
            // is resolved once and passed for each.
            sb.AppendLine(createSignature);
            sb.AppendLine("    {");
            var mapperLocals = new Dictionary<string, string>(System.StringComparer.Ordinal);
            foreach (var mapping in errorMappings)
            {
                if (!mapperLocals.TryGetValue(mapping.MapperTypeName, out var local))
                {
                    local = "__errorMapper" + mapperLocals.Count.ToString(CultureInfo.InvariantCulture);
                    mapperLocals[mapping.MapperTypeName] = local;
                    sb.AppendLine($"        var {local} = {GetRequired}<{mapping.MapperTypeName}>(services);");
                }
                ctorArgs.Add(local);
            }
            sb.AppendLine($"        return new {model.ClassName}(");
            for (var i = 0; i < ctorArgs.Count; i++)
                sb.AppendLine($"            {ctorArgs[i]}{(i < ctorArgs.Count - 1 ? "," : ");")}");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        sb.AppendLine($"    static void {self}.AddSerializers(global::Microsoft.Extensions.DependencyInjection.IServiceCollection services, global::ZeroAlloc.Rest.ZeroAllocClientOptions options)");
        sb.AppendLine("    {");
        if (model.SerializerTypeName != null)
        {
            // The interface-level [Serializer] fixes this client's serializer at compile time, so a
            // UseSerializer for it is a contradiction: reject it instead of ignoring it.
            var interfaceFullName = string.IsNullOrEmpty(model.Namespace)
                ? model.InterfaceName
                : model.Namespace + "." + model.InterfaceName;
            var serializerDisplayName = StripGlobal(model.SerializerTypeName);
            sb.AppendLine("        if (options.SerializerType is not null || options.SerializerInstance is not null)");
            sb.AppendLine("            throw new global::System.InvalidOperationException(");
            sb.AppendLine($"                \"The REST client '{interfaceFullName}' declares [Serializer(typeof({serializerDisplayName}))], \" +");
            sb.AppendLine("                \"so it cannot also be given a serializer with UseSerializer. Use one or the other.\");");
            sb.AppendLine($"        {TryAddSingleton}<{model.SerializerTypeName}>(services);");
        }
        else
        {
            // UseSerializer is per client: keyed by the interface, it never touches the app-wide
            // IRestSerializer, so two clients cannot overwrite each other's serializer.
            sb.AppendLine($"        global::ZeroAlloc.Rest.GeneratedRestClientRegistration.AddPerClientSerializer<{model.InterfaceName}>(services, options);");
        }
        foreach (var st in overrideSerializers)
            sb.AppendLine($"        {TryAddSingleton}<{st}>(services);");
        // Every usable [ErrorMapper], used or not, by its concrete type. Create resolves that type, so
        // a host registration of IHttpErrorMapper<E> is never consulted.
        var registeredMappers = new List<string>();
        foreach (var mapper in model.ErrorMappers)
        {
            if (registeredMappers.Contains(mapper.MapperTypeName))
                continue;
            registeredMappers.Add(mapper.MapperTypeName);
            sb.AppendLine($"        {TryAddSingleton}<{mapper.MapperTypeName}>(services);");
        }
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    // Returns true when the method has a CancellationToken parameter, so its body calls
    // __RecordCancellation.
    private static bool EmitMethod(SourceProductionContext ctx, StringBuilder sb, string interfaceName, MethodModel method, IReadOnlyDictionary<string, string> serializerFieldMap, IReadOnlyDictionary<string, string> errorMapperFieldMap, int maxErrorBodyBytes)
    {
        var ctParam = FindCancellationToken(method.Parameters);
        var ctArg = ctParam != null ? Identifier(ctParam) : "default";
        var pathParams = FilterParameters(method.Parameters, ParameterKind.Path);
        var queryParams = FilterParameters(method.Parameters, ParameterKind.Query);
        var bodyParam = FirstOrDefault(method.Parameters, ParameterKind.Body);
        var formBodyParam = FirstOrDefault(method.Parameters, ParameterKind.FormBody);
        var headerParams = FilterParameters(method.Parameters, ParameterKind.Header);

        if (bodyParam != null && formBodyParam != null)
        {
            ctx.ReportDiagnostic(Diagnostic.Create(DiagnosticDescriptors.ConflictingBody, method.Location?.ToLocation(), method.Name));
            // Still emit valid (if incomplete) code so compilation continues
            formBodyParam = null; // suppress the FormBody branch
        }

        // If the method has its own [Serializer], use that injected field; otherwise fall back to _serializer.
        var serializerExpr = method.SerializerTypeName != null && serializerFieldMap.TryGetValue(method.SerializerTypeName, out var fieldName)
            ? fieldName
            : "_serializer";

        string? errorMapperField = null;
        if (method.MapsError)
        {
            var errorTypeName = method.ErrorTypeName
                ?? throw new global::System.InvalidOperationException("MapsError implies ErrorTypeName is set.");
            if (!errorMapperFieldMap.TryGetValue(errorTypeName, out errorMapperField))
            {
                EmitUnmappedStub(sb, method);
                return false;
            }
        }

        sb.AppendLine($"    public async {method.ReturnTypeName} {method.Name}({BuildParamList(method.Parameters)})");
        sb.AppendLine("    {");

        var spanName = $"{interfaceName}.{method.Name}";
        sb.AppendLine($"        using var __activity = _activitySource.StartActivity(\"{spanName}\");");
        sb.AppendLine($"        const string __RestMethodTag = \"{spanName}\";");
        sb.AppendLine($"        const string __httpMethod = \"{method.HttpMethod.ToUpper()}\";");
        sb.AppendLine($"        __activity?.SetTag(\"http.method\", __httpMethod);");
        sb.AppendLine($"        __activity?.SetTag(\"rest.method\", __RestMethodTag);");
        sb.AppendLine($"        var __sw = global::System.Diagnostics.Stopwatch.GetTimestamp();");

        // Every local the generated method declares starts with "__", and every parameter is emitted
        // through Identifier, so a parameter named url, request, response or @class still compiles.
        EmitUrlBuilding(sb, method.Route, pathParams, queryParams, method.EvaluatedRouteTokens);
        EmitRequestCreation(sb, method, headerParams, formBodyParam, serializerExpr);
        // Serializing a [Body] is part of the call, so it runs inside the method's try: a serializer
        // failure or a caller cancellation is traced and timed like any other.
        var bodyStatement = bodyParam is null
            ? null
            : $"__request.Content = await global::ZeroAlloc.Rest.GeneratedRestClient.CreateBodyContentAsync({serializerExpr}, {Identifier(bodyParam)}, {ctArg}).ConfigureAwait(false);";
        EmitSendAndResponse(sb, method, ctParam is null ? null : Identifier(ctParam), bodyStatement, serializerExpr, maxErrorBodyBytes, errorMapperField);

        sb.AppendLine("    }");
        sb.AppendLine();
        return ctParam != null;
    }

    // One __FormatValue overload per type a route, query or header value has, so a value is written
    // the same wherever it goes: invariant culture, ISO 8601 dates and times, lower-case booleans, and
    // an enum member's [JsonStringEnumMemberName]. A value type also gets a Nullable<T> overload, which
    // the null-checked call sites bind to.
    private static void EmitFormatHelpers(StringBuilder sb, ClientModel model)
    {
        var emitted = new HashSet<string>(System.StringComparer.Ordinal);
        var anyExplicit = false;
        foreach (var method in model.Methods)
        {
            foreach (var parameter in method.Parameters)
            {
                if (parameter.Format is { } format && emitted.Add(format.TypeName))
                {
                    EmitFormatHelper(sb, format);
                    anyExplicit |= format.Format == ValueFormat.ExplicitInvariant;
                }
            }
        }

        // A type that implements IFormattable explicitly has no public ToString(format, provider), so
        // it is called through the interface; the constraint keeps a struct from being boxed.
        if (anyExplicit)
        {
            sb.AppendLine("    private static string __FormatFormattable<T>(T value) where T : global::System.IFormattable");
            sb.AppendLine("        => value.ToString(null, global::System.Globalization.CultureInfo.InvariantCulture);");
            sb.AppendLine();
        }
    }

    private static void EmitFormatHelper(StringBuilder sb, ValueFormatModel format)
    {
        var type = format.TypeName;
        sb.Append("    private static string __FormatValue(").Append(type).Append(" value) => ");
        switch (format.Format)
        {
            case ValueFormat.String:
                sb.AppendLine("value;");
                break;
            case ValueFormat.Boolean:
                sb.AppendLine("value ? \"true\" : \"false\";");
                break;
            case ValueFormat.Iso8601:
                sb.AppendLine("value.ToString(\"O\", global::System.Globalization.CultureInfo.InvariantCulture);");
                break;
            case ValueFormat.Invariant:
                sb.AppendLine("value.ToString(null, global::System.Globalization.CultureInfo.InvariantCulture);");
                break;
            case ValueFormat.ExplicitInvariant:
                sb.AppendLine("__FormatFormattable(value);");
                break;
            case ValueFormat.Enum:
                EmitEnumFormat(sb, format);
                break;
            default:
                // object.ToString and ValueType.ToString are annotated as returning string?.
                sb.AppendLine("value.ToString() ?? string.Empty;");
                break;
        }
        if (format.IsValueType)
            sb.AppendLine($"    private static string __FormatValue({type}? value) => value.HasValue ? __FormatValue(value.GetValueOrDefault()) : string.Empty;");
        sb.AppendLine();
    }

    // An enum is written as System.Text.Json's JsonStringEnumConverter writes it: a member's
    // [JsonStringEnumMemberName] or C# name; for a [Flags] combination, the names of the members it
    // consumes, walked in STJ's order and joined with ", "; and anything else as its number.
    private static void EmitEnumFormat(StringBuilder sb, ValueFormatModel format)
    {
        var type = format.TypeName;
        var number = $"(({format.EnumUnderlyingType})value).ToString(global::System.Globalization.CultureInfo.InvariantCulture)";
        if (!format.IsFlags)
        {
            sb.AppendLine("value switch");
            sb.AppendLine("    {");
            foreach (var member in format.EnumMembers)
                sb.AppendLine($"        {type}.{EscapeKeyword(member.Member)} => {Literal(member.Wire)},");
            sb.AppendLine($"        _ => {number},");
            sb.AppendLine("    };");
            return;
        }

        sb.AppendLine("__FormatFlags(value);");
        sb.AppendLine($"    private static string __FormatFlags({type} value)");
        sb.AppendLine("    {");
        if (format.EnumMembers.Count > 0)
        {
            sb.AppendLine("        switch (value)");
            sb.AppendLine("        {");
            foreach (var member in format.EnumMembers)
                sb.AppendLine($"            case {type}.{EscapeKeyword(member.Member)}: return {Literal(member.Wire)};");
            sb.AppendLine("        }");
        }
        sb.AppendLine($"        var __bits = unchecked((ulong)({format.EnumUnderlyingType})value);");
        sb.AppendLine("        string? __text = null;");
        foreach (var member in format.EnumMembers)
        {
            if (member.Key == 0) continue;
            var key = "0x" + member.Key.ToString("X", CultureInfo.InvariantCulture) + "UL";
            var wire = Literal(member.Wire);
            sb.AppendLine($"        if ((__bits & {key}) == {key}) {{ __bits &= ~{key}; __text = __text is null ? {wire} : __text + \", \" + {wire}; }}");
        }
        sb.AppendLine($"        return __bits == 0 && __text is not null ? __text : {number};");
        sb.AppendLine("    }");
    }

    private static string Literal(string value)
        => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, quote: true);

    private static string EscapeKeyword(string name)
        => Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(name) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None
            ? "@" + name
            : name;

    private static void EmitUrlBuilding(StringBuilder sb, string route,
        List<ParameterModel> pathParams, List<ParameterModel> queryParams, EquatableArray<string> evaluatedTokens)
    {
        if (pathParams.Count == 0 && queryParams.Count == 0)
        {
            var literal = new StringBuilder(route.Length);
            AppendLiteral(literal, route, interpolated: false);
            sb.AppendLine($"        var __url = \"{literal}\";");
            return;
        }

        var routeExpr = RouteExpression(route, pathParams, evaluatedTokens);

        if (queryParams.Count == 0)
        {
            sb.AppendLine($"        var __url = $\"{routeExpr}\";");
        }
        else
        {
            sb.AppendLine($"        var __urlBase = $\"{routeExpr}\";");
            sb.AppendLine("        using var __urlBuilder = new ZeroAlloc.Collections.HeapPooledList<char>(__urlBase.Length + 64);");
            sb.AppendLine("        AppendToUrl(__urlBuilder, __urlBase.AsSpan());");
            sb.AppendLine("        var __hasQuery = false;");
            foreach (var q in queryParams)
            {
                if (q.IsCollection)
                {
                    sb.AppendLine($"        if ({Identifier(q)} != null)");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            foreach (var __item in {Identifier(q)})");
                    sb.AppendLine("            {");
                    if (q.Format is not { ElementIsNullable: false })
                        sb.AppendLine("                if (__item == null) continue;");
                    sb.AppendLine($"                AppendToUrl(__urlBuilder, __hasQuery ? '&' : '?');");
                    sb.AppendLine($"                AppendToUrl(__urlBuilder, \"{q.QueryName}=\".AsSpan());");
                    sb.AppendLine($"                AppendToUrl(__urlBuilder, global::System.Uri.EscapeDataString(__FormatValue(__item)).AsSpan());");
                    sb.AppendLine("                __hasQuery = true;");
                    sb.AppendLine("            }");
                    sb.AppendLine("        }");
                }
                else if (q.IsNullable)
                {
                    sb.AppendLine($"        if ({Identifier(q)} != null)");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            AppendToUrl(__urlBuilder, __hasQuery ? '&' : '?');");
                    sb.AppendLine($"            AppendToUrl(__urlBuilder, \"{q.QueryName}=\".AsSpan());");
                    sb.AppendLine($"            AppendToUrl(__urlBuilder, global::System.Uri.EscapeDataString(__FormatValue({Identifier(q)})).AsSpan());");
                    sb.AppendLine("            __hasQuery = true;");
                    sb.AppendLine("        }");
                }
                else
                {
                    sb.AppendLine($"        AppendToUrl(__urlBuilder, __hasQuery ? '&' : '?');");
                    sb.AppendLine($"        AppendToUrl(__urlBuilder, \"{q.QueryName}=\".AsSpan());");
                    sb.AppendLine($"        AppendToUrl(__urlBuilder, global::System.Uri.EscapeDataString(__FormatValue({Identifier(q)})).AsSpan());");
                    sb.AppendLine("        __hasQuery = true;");
                }
            }
            sb.AppendLine("        var __url = new string(__urlBuilder.AsReadOnlySpan());");
        }
    }

    private static void EmitRequestCreation(StringBuilder sb, MethodModel method,
        List<ParameterModel> headerParams, ParameterModel? formBodyParam, string serializerExpr)
    {
        sb.AppendLine($"        using var __request = new System.Net.Http.HttpRequestMessage(");
        sb.AppendLine($"            System.Net.Http.HttpMethod.{Capitalize(method.HttpMethod)},");
        sb.AppendLine($"            __url);");
        sb.AppendLine($"        __request.Headers.Accept.Add(new System.Net.Http.Headers.MediaTypeWithQualityHeaderValue({serializerExpr}.ContentType));");

        // Static headers declared with [Header("Name", Value = "...")] are added additively.
        // For Accept, this means both the serializer's content type and the static value will
        // appear in the header. This is intentional — use ConfigureHttpClient to override
        // the serializer's Accept if exclusive control is needed.
        foreach (var (name, value) in method.StaticHeaders)
            sb.AppendLine($"        __request.Headers.TryAddWithoutValidation(\"{name}\", \"{value}\");");

        // TryAddWithoutValidation sends a null value as an empty header, so a parameter that can be
        // null is added only when it has a value: a null argument means "no header". A non-nullable
        // value type always has one, and comparing it with null would not compile cleanly.
        // A collection adds each non-null element as one value of the header, which HttpClient sends
        // comma-joined, the RFC 9110 list syntax; a null or empty collection sends no header.
        foreach (var h in headerParams)
        {
            if (h.IsCollection)
            {
                sb.AppendLine($"        if ({Identifier(h)} != null)");
                sb.AppendLine("        {");
                sb.AppendLine($"            foreach (var __item in {Identifier(h)})");
                sb.AppendLine("            {");
                if (h.Format is not { ElementIsNullable: false })
                    sb.AppendLine("                if (__item == null) continue;");
                sb.AppendLine($"                __request.Headers.TryAddWithoutValidation(\"{h.HeaderName}\", __FormatValue(__item));");
                sb.AppendLine("            }");
                sb.AppendLine("        }");
                continue;
            }

            var addHeader = $"__request.Headers.TryAddWithoutValidation(\"{h.HeaderName}\", __FormatValue({Identifier(h)}));";
            if (h.IsNullable)
            {
                sb.AppendLine($"        if ({Identifier(h)} is not null)");
                sb.AppendLine($"            {addHeader}");
            }
            else
            {
                sb.AppendLine($"        {addHeader}");
            }
        }

        if (formBodyParam != null)
        {
            sb.AppendLine($"        __request.Content = new System.Net.Http.FormUrlEncodedContent({Identifier(formBodyParam)});");
        }
    }

    // callerToken is the name of the method's CancellationToken parameter, or null when it has none.
    // bodyStatement serializes the [Body] parameter into the request, or is null when there is none.
    private static void EmitSendAndResponse(StringBuilder sb, MethodModel method, string? callerToken, string? bodyStatement, string serializerExpr, int maxErrorBodyBytes, string? errorMapperField)
    {
        var ctArg = callerToken ?? "default";
        if (errorMapperField != null)
            sb.AppendLine("        global::ZeroAlloc.Rest.HttpError __httpError;");
        // Set once the response's duration is recorded, so a failure after that point does not
        // record the duration a second time.
        sb.AppendLine("        var __durationRecorded = false;");
        // A Result method tells a serializer failure from a failure of the send by where it
        // happened, not by its type: a serializer may throw anything, an HttpRequestException too.
        var guardBody = bodyStatement != null && method.ReturnsResult;
        if (guardBody)
            sb.AppendLine("        var __writingBody = true;");
        sb.AppendLine("        try");
        sb.AppendLine("        {");
        if (bodyStatement != null)
        {
            // Serialized into a pooled buffer that the request owns: disposing the request returns
            // it. The helper returns the buffer itself when the serializer throws or is cancelled.
            sb.AppendLine($"            {bodyStatement}");
            if (guardBody)
                sb.AppendLine("            __writingBody = false;");
        }
        sb.AppendLine($"            using var __response = await _httpClient.SendAsync(__request, {ctArg}).ConfigureAwait(false);");
        sb.AppendLine("            var __statusCode = (int)__response.StatusCode;");
        sb.AppendLine("            var __serverAddress = __request.RequestUri?.Host ?? string.Empty;");
        sb.AppendLine("            __activity?.SetTag(\"http.status_code\", __statusCode);");
        sb.AppendLine("            __activity?.SetTag(\"server.address\", __serverAddress);");
        sb.AppendLine("            var __elapsedMs = global::System.Diagnostics.Stopwatch.GetElapsedTime(__sw).TotalMilliseconds;");
        sb.AppendLine("            _requestsTotal.Add(1,");
        sb.AppendLine("                new global::System.Collections.Generic.KeyValuePair<string, object?>(\"http.method\", __httpMethod),");
        sb.AppendLine("                new global::System.Collections.Generic.KeyValuePair<string, object?>(\"http.status_code\", __statusCode),");
        sb.AppendLine("                new global::System.Collections.Generic.KeyValuePair<string, object?>(\"server.address\", __serverAddress),");
        sb.AppendLine("                new global::System.Collections.Generic.KeyValuePair<string, object?>(\"rest.method\", __RestMethodTag));");
        sb.AppendLine("            _requestDurationMs.Record(__elapsedMs,");
        sb.AppendLine("                new global::System.Collections.Generic.KeyValuePair<string, object?>(\"http.method\", __httpMethod),");
        sb.AppendLine("                new global::System.Collections.Generic.KeyValuePair<string, object?>(\"http.status_code\", __statusCode),");
        sb.AppendLine("                new global::System.Collections.Generic.KeyValuePair<string, object?>(\"server.address\", __serverAddress),");
        sb.AppendLine("                new global::System.Collections.Generic.KeyValuePair<string, object?>(\"rest.method\", __RestMethodTag));");
        sb.AppendLine("            __durationRecorded = true;");
        EmitResponseHandling(sb, method, ctArg, serializerExpr, maxErrorBodyBytes, indent: "            ");
        sb.AppendLine("        }");
        // Cancellation the caller asked for is not an error: the span keeps status Unset and is
        // tagged instead. It still throws, from Result methods too.
        if (callerToken != null)
        {
            sb.AppendLine($"        catch (global::System.OperationCanceledException) when ({callerToken}.IsCancellationRequested)");
            sb.AppendLine("        {");
            sb.AppendLine("            __RecordCancellation(__activity, __sw, __httpMethod, __RestMethodTag, __durationRecorded);");
            sb.AppendLine("            throw;");
            sb.AppendLine("        }");
        }
        if (guardBody)
            EmitBodySerializationCatch(sb, method);
        if (method.ReturnsResult)
            EmitResultCatches(sb, method);
        sb.AppendLine("        catch (global::System.Exception __ex)");
        sb.AppendLine("        {");
        sb.AppendLine("            __RecordFailure(__activity, __ex, __sw, __httpMethod, __RestMethodTag, __durationRecorded);");
        sb.AppendLine("            throw;");
        sb.AppendLine("        }");
        if (errorMapperField != null)
            EmitMapping(sb, method, errorMapperField);
    }

    // A Result method returns a request body the serializer could not write as a Deserialization
    // failure with no response, the kind for any serializer failure. Cancellation is left to the
    // method's cancellation catches, as it is for reading the response body: the caller's still
    // throws, and any other is a Timeout.
    private static void EmitBodySerializationCatch(StringBuilder sb, MethodModel method)
    {
        sb.AppendLine("        catch (global::System.Exception __ex) when (__writingBody && __ex is not global::System.OperationCanceledException)");
        sb.AppendLine("        {");
        sb.AppendLine("            __RecordFailure(__activity, __ex, __sw, __httpMethod, __RestMethodTag, __durationRecorded);");
        EmitFailure(sb, "            ", method, "__CreateHttpError(global::ZeroAlloc.Rest.HttpErrorKind.Deserialization, null, __ex)");
        sb.AppendLine("        }");
    }

    // A Result-returning method returns a failure for a timeout or a transport error instead of
    // throwing. Cancellation the caller asked for is caught before these and still throws. Anything
    // else, such as a bug in a handler, reaches the rethrowing catch that follows these.
    private static void EmitResultCatches(StringBuilder sb, MethodModel method)
    {
        // Not requested by the caller, so it is HttpClient.Timeout or another timeout in the pipeline.
        sb.AppendLine("        catch (global::System.OperationCanceledException __ex)");
        sb.AppendLine("        {");
        sb.AppendLine("            __RecordFailure(__activity, __ex, __sw, __httpMethod, __RestMethodTag, __durationRecorded);");
        EmitFailure(sb, "            ", method, "__CreateHttpError(global::ZeroAlloc.Rest.HttpErrorKind.Timeout, null, __ex)");
        sb.AppendLine("        }");
        sb.AppendLine("        catch (global::System.Net.Http.HttpRequestException __ex)");
        sb.AppendLine("        {");
        sb.AppendLine("            __RecordFailure(__activity, __ex, __sw, __httpMethod, __RestMethodTag, __durationRecorded);");
        EmitFailure(sb, "            ", method, "__CreateHttpError(global::ZeroAlloc.Rest.HttpErrorKind.Transport, null, __ex)");
        sb.AppendLine("        }");
    }

    private static void EmitResponseHandling(StringBuilder sb, MethodModel method, string ctArg, string serializerExpr, int maxErrorBodyBytes, string indent = "        ")
    {
        var i1 = indent + "    ";
        var i2 = i1 + "    ";
        if (method.ReturnsVoid)
        {
            sb.AppendLine($"{indent}__response.EnsureSuccessStatusCode();");
        }
        else if (method.ReturnsUnitResult)
        {
            // No body to read, so nothing can fail to deserialize: success is the status alone.
            sb.AppendLine($"{indent}if (__response.IsSuccessStatusCode)");
            sb.AppendLine($"{indent}{{");
            sb.AppendLine($"{i1}return {ResultTypeName(method)}.Success();");
            sb.AppendLine($"{indent}}}");
            sb.AppendLine($"{indent}else");
            sb.AppendLine($"{indent}{{");
            EmitStatusFailure(sb, method, i1, ctArg, maxErrorBodyBytes);
            sb.AppendLine($"{indent}}}");
        }
        else if (method.ReturnsResult)
        {
            var resultType = ResultTypeName(method);
            sb.AppendLine($"{indent}if (__response.IsSuccessStatusCode)");
            sb.AppendLine($"{indent}{{");
            sb.AppendLine($"{i1}var __responseStream = await __response.Content.ReadAsStreamAsync({ctArg}).ConfigureAwait(false);");
            // Only the deserialize call is guarded: whatever the serializer throws, a JsonException or
            // a MemoryPack or MessagePack exception, means the body could not be read. Cancellation
            // is left to the method's cancellation catches.
            if (method.MapsError)
            {
                // The success return stays inside the try, so the catch can store the error and fall
                // through to the single mapping site after the method's try.
                sb.AppendLine($"{i1}try");
                sb.AppendLine($"{i1}{{");
                EmitEmptyBodyCheck(sb, method, i2);
                sb.AppendLine($"{i2}{method.InnerTypeName} __content = {ReadBody(method, serializerExpr, ctArg)};");
                sb.AppendLine($"{i2}return {resultType}.Success(__content);");
                sb.AppendLine($"{i1}}}");
            }
            else
            {
                sb.AppendLine($"{i1}{method.InnerTypeName} __content;");
                sb.AppendLine($"{i1}try");
                sb.AppendLine($"{i1}{{");
                EmitEmptyBodyCheck(sb, method, i2);
                sb.AppendLine($"{i2}__content = {ReadBody(method, serializerExpr, ctArg)};");
                sb.AppendLine($"{i1}}}");
            }
            sb.AppendLine($"{i1}catch (global::System.Exception __ex) when (__ex is not global::System.OperationCanceledException)");
            sb.AppendLine($"{i1}{{");
            sb.AppendLine($"{i2}__RecordFailure(__activity, __ex, __sw, __httpMethod, __RestMethodTag, __durationRecorded);");
            EmitFailure(sb, i2, method, "__CreateHttpError(global::ZeroAlloc.Rest.HttpErrorKind.Deserialization, __response, __ex)");
            sb.AppendLine($"{i1}}}");
            if (!method.MapsError)
                sb.AppendLine($"{i1}return {resultType}.Success(__content);");
            sb.AppendLine($"{indent}}}");
            sb.AppendLine($"{indent}else");
            sb.AppendLine($"{indent}{{");
            EmitStatusFailure(sb, method, i1, ctArg, maxErrorBodyBytes);
            sb.AppendLine($"{indent}}}");
        }
        else
        {
            sb.AppendLine($"{indent}__response.EnsureSuccessStatusCode();");
            sb.AppendLine($"{indent}var __responseStream = await __response.Content.ReadAsStreamAsync().ConfigureAwait(false);");
            EmitEmptyBodyCheck(sb, method, indent);
            sb.AppendLine($"{indent}return {ReadBody(method, serializerExpr, ctArg)};");
        }
    }

    // A success body of JSON null, or an empty one such as a 204's, has no value. A T that accepts
    // null gets null. Otherwise the read throws, and a Result method's deserialization catch turns
    // that into a Deserialization failure: a null never reaches the caller as a T that denies it.
    // A reference T is checked after the read, which gives null for both. A value T reads an empty
    // body as default, so the empty body is checked before the read; JSON null already throws.
    private static string ReadBody(MethodModel method, string serializerExpr, string ctArg)
    {
        var read = $"await {serializerExpr}.DeserializeAsync<{method.InnerTypeName}>(__responseStream, {ctArg}).ConfigureAwait(false)";
        return method.InnerTypeIsNullable || method.InnerTypeIsValueType
            ? read
            : $"({read}) ?? throw new global::System.InvalidOperationException({NullBodyMessage(method)})";
    }

    private static void EmitEmptyBodyCheck(StringBuilder sb, MethodModel method, string indent)
    {
        if (method.InnerTypeIsNullable || !method.InnerTypeIsValueType)
            return;
        sb.AppendLine($"{indent}if (__responseStream.CanSeek && __responseStream.Position >= __responseStream.Length)");
        sb.AppendLine($"{indent}    throw new global::System.InvalidOperationException({NullBodyMessage(method)});");
    }

    private static string NullBodyMessage(MethodModel method)
        => Literal($"{method.Name} received an empty or null response body, but its success type {method.InnerTypeName} "
            + $"does not accept null. Declare {method.InnerTypeName}? to accept an empty body.");

    // A non-success status: read the capped body, when asked, before the response is disposed.
    private static void EmitStatusFailure(StringBuilder sb, MethodModel method, string indent, string ctArg, int maxErrorBodyBytes)
    {
        if (maxErrorBodyBytes > 0)
        {
            // The helper caps the body, turns a failed read into an empty body, and still throws on
            // caller cancellation.
            var cap = maxErrorBodyBytes.ToString(CultureInfo.InvariantCulture);
            sb.AppendLine($"{indent}var __errorBody = await global::ZeroAlloc.Rest.GeneratedRestClient.ReadErrorBodyAsync(__response.Content, {cap}, {ctArg}).ConfigureAwait(false);");
            EmitFailure(sb, indent, method, "__CreateHttpError(global::ZeroAlloc.Rest.HttpErrorKind.Status, __response, null, __errorBody.Body, __errorBody.Truncated)");
        }
        else
        {
            EmitFailure(sb, indent, method, "__CreateHttpError(global::ZeroAlloc.Rest.HttpErrorKind.Status, __response, null)");
        }
    }

    // A mapped method repeats its E as declared, nullable annotation included: Result<T, E> and
    // UnitResult<E> are structs, so Result<T, JevError> does not convert to Result<T, JevError?>.
    private static string ResultTypeName(MethodModel method)
    {
        var error = method.MapsError ? method.DeclaredErrorTypeName : "ZeroAlloc.Rest.HttpError";
        return method.ReturnsUnitResult
            ? $"ZeroAlloc.Results.UnitResult<{error}>"
            : $"ZeroAlloc.Results.Result<{method.InnerTypeName}, {error}>";
    }

    // How a failure site ends. An HttpError method returns the error from the site, exactly as
    // before. A mapped method stores it in __httpError and maps it once, after the method's try.
    private static void EmitFailure(StringBuilder sb, string indent, MethodModel method, string createCall)
    {
        if (method.MapsError)
        {
            sb.AppendLine($"{indent}__httpError = {createCall};");
        }
        else
        {
            sb.AppendLine($"{indent}return {ResultTypeName(method)}.Failure(");
            sb.AppendLine($"{indent}    {createCall});");
        }
    }

    // The one mapping site. It sits outside the method's try, so a mapper's exception never reaches
    // the Result catches and is never mapped again. The exception reaches the caller unchanged,
    // and the span is marked failed.
    private static void EmitMapping(StringBuilder sb, MethodModel method, string errorMapperField)
    {
        var mapped = $"{errorMapperField}.Map(__httpError)";
        if (method.MappedErrorNeedsNullCheck)
        {
            // The mapper is declared over E? but the method returns a non-nullable E. A null would
            // break the method's contract, so it fails loudly here instead of reaching the caller.
            var mapperError = StripGlobal(method.MapperErrorTypeName
                ?? throw new global::System.InvalidOperationException("MappedErrorNeedsNullCheck requires MapperErrorTypeName."));
            var methodError = StripGlobal(method.DeclaredErrorTypeName
                ?? throw new global::System.InvalidOperationException("MappedErrorNeedsNullCheck requires DeclaredErrorTypeName."));
            mapped += $" ?? throw new global::System.InvalidOperationException(\"The IHttpErrorMapper<{mapperError}> returned null, but {method.Name} returns a Result whose error type {methodError} is not nullable.\")";
        }
        sb.AppendLine("        try");
        sb.AppendLine("        {");
        sb.AppendLine($"            return {ResultTypeName(method)}.Failure({mapped});");
        sb.AppendLine("        }");
        sb.AppendLine("        catch (global::System.Exception __ex)");
        sb.AppendLine("        {");
        sb.AppendLine("            __RecordMapperFailure(__activity, __ex);");
        sb.AppendLine("            throw;");
        sb.AppendLine("        }");
    }

